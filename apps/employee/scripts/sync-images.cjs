/**
 * Copies the Worker app's images from docs/Design/images (named exactly as in
 * docs/Design/Image_Shot_List.md) into assets/images and regenerates
 * src/assets/images.generated.ts. Missing files stay null, so the app shows
 * the designed fallback instead of failing the bundle.
 *
 *   node scripts/sync-images.cjs
 */
const fs = require('node:fs');
const path = require('node:path');

const NAMES = [
  'wrk-onboarding-hero.jpg',
  'wrk-team.jpg',
  'wrk-training-1.jpg',
  'wrk-training-2.jpg',
  'wrk-training-3.jpg',
  'svc-maid.jpg',
  'svc-cook.jpg',
  'svc-caretaker.jpg',
  'community-towers.jpg',
  'ill-verify-review.png',
  'ill-verified.png',
  'ill-rejected.png',
  'ill-offline.png',
  'ill-empty-visits.png',
  'ill-checkin-phone.png',
  'ill-visit-done.png',
  'ill-overtime.png',
  'ill-leave.png',
  'ill-payslip.png',
  'ill-training.png',
  'ill-applicant.png',
];

const app = path.resolve(__dirname, '..');
const src = path.resolve(app, '../../docs/Design/images');
const dest = path.join(app, 'assets/images');
fs.mkdirSync(dest, { recursive: true });

const lines = [];
let found = 0;
for (const file of NAMES) {
  const key = file.replace(/\.(jpg|png)$/, '');
  const from = path.join(src, file);
  // Accept .jpg/.png/.jpeg/.webp variants of the same name.
  const alt = ['.jpg', '.jpeg', '.png', '.webp'].map((x) => path.join(src, key + x)).find((p) => fs.existsSync(p));
  const actual = fs.existsSync(from) ? from : alt;
  if (actual) {
    const out = key + path.extname(actual);
    fs.copyFileSync(actual, path.join(dest, out));
    lines.push(`  '${key}': require('../../assets/images/${out}'),`);
    found++;
  } else {
    lines.push(`  '${key}': null,`);
  }
}

const ts = `/* eslint-disable @typescript-eslint/no-require-imports */
// Generated by scripts/sync-images.cjs from docs/Design/images. Do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

export const GENERATED_IMAGES = {
${lines.join('\n')}
} as const satisfies Record<string, ImageSourcePropType | null>;
`;
fs.writeFileSync(path.join(app, 'src/assets/images.generated.ts'), ts);
console.log(`images: ${found}/${NAMES.length} found in docs/Design/images`);
