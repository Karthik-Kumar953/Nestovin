/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS config read by Node/Metro */
/**
 * Copies the owner's generated images (docs/Design/images/) that appear in the shot list into
 * apps/resident/assets/images/ and rewrites src/assets/images.generated.ts with static requires.
 * Only files that exist are required, so Metro never fails on a missing image.
 * Usage: `pnpm images` (from apps/resident).
 */
const fs = require('node:fs');
const path = require('node:path');

const app = path.resolve(__dirname, '..');
const source = path.resolve(app, '../../docs/Design/images');
const target = path.join(app, 'assets/images');
const registry = fs.readFileSync(path.join(app, 'src/assets/images.ts'), 'utf8');
const listBlock = registry.slice(registry.indexOf('SHOT_LIST = ['), registry.indexOf('] as const'));
const names = [...listBlock.matchAll(/'([^']+\.(?:jpg|jpeg|png|webp))'/g)].map((m) => m[1]);

fs.mkdirSync(target, { recursive: true });
const found = [];
for (const name of names) {
  const from = path.join(source, name);
  if (fs.existsSync(from)) {
    fs.copyFileSync(from, path.join(target, name));
    found.push(name);
  }
}

const lines = found.map((n) => `  '${n}': require('../../assets/images/${n}'),`);
const out = [
  '// Generated by scripts/sync-images.cjs. Do not edit by hand; run `pnpm images` after adding files to docs/Design/images/.',
  '/* eslint-disable @typescript-eslint/no-require-imports */',
  'const images: Record<string, number> = {',
  ...lines,
  '};',
  'export default images;',
  '',
].join('\n');
fs.writeFileSync(path.join(app, 'src/assets/images.generated.ts'), found.length ? out : out.replace("/* eslint-disable @typescript-eslint/no-require-imports */\n", ''));
console.warn(`images: ${found.length} of ${names.length} shot-list files present (${names.length - found.length} use designed fallbacks).`);
