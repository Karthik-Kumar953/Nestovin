import { z } from 'zod';
import { uuidSchema } from './common';

/*
 * Phase 6: attendance (EMP-06, ADR-014), completion (EMP-07), service history
 * and feedback (RES-10/11), records, corrections and no-shows (ADM-12/12A).
 */

export const visitCodeSchema = z.object({
  occurrenceId: uuidSchema,
  /** 6-digit code the worker types in. */
  otp: z.string(),
  /** Payload for the QR the worker scans. */
  qr: z.string(),
  expiresAt: z.string(),
});
export type VisitCode = z.infer<typeof visitCodeSchema>;

export const checkInSchema = z.object({
  method: z.enum(['OTP', 'QR']),
  code: z.string().trim().min(6).max(200),
  lat: z.number().min(-90).max(90).optional(),
  lng: z.number().min(-180).max(180).optional(),
  accuracyM: z.number().min(0).max(100000).optional(),
  deviceTime: z.iso.datetime({ offset: true }).optional(),
  /** Generated by the app per attempt; makes retries idempotent. */
  clientEventId: z.string().min(8).max(64),
});
export type CheckInInput = z.infer<typeof checkInSchema>;

export const checkInResultSchema = z.object({
  result: z.enum(['VERIFIED', 'REJECTED']),
  message: z.string(),
  flags: z.array(z.string()),
});
export type CheckInResult = z.infer<typeof checkInResultSchema>;

export const completeVisitSchema = z.object({ note: z.string().trim().max(1000).optional() });
export const residentAbsentSchema = z.object({
  note: z.string().trim().max(500).optional(),
  lat: z.number().min(-90).max(90).optional(),
  lng: z.number().min(-180).max(180).optional(),
});
export const correctionRequestSchema = z.object({
  requestedChange: z.enum(['MARK_ATTENDED', 'MARK_COMPLETED']),
  explanation: z.string().trim().min(5).max(1000),
});

export const residentVisitSchema = z.object({
  occurrenceId: uuidSchema,
  scheduledDate: z.string(),
  startsAt: z.string().nullable(),
  serviceName: z.string(),
  status: z.string(),
  workerName: z.string().nullable(),
  checkedInAt: z.string().nullable(),
  completedAt: z.string().nullable(),
  noShow: z.enum(['RESIDENT_ABSENT', 'WORKER_ABSENT']).nullable(),
  feedback: z.object({ rating: z.number().int(), comment: z.string().nullable() }).nullable(),
  /** True when the resident can show a check-in code now. */
  canShowCode: z.boolean(),
});
export type ResidentVisit = z.infer<typeof residentVisitSchema>;

export const feedbackSchema = z.object({ rating: z.number().int().min(1).max(5), comment: z.string().trim().max(1000).optional() });

export const attendanceRecordSchema = z.object({
  occurrenceId: uuidSchema,
  scheduledDate: z.string(),
  startsAt: z.string().nullable(),
  status: z.string(),
  serviceName: z.string(),
  flat: z.object({ flatNumber: z.string(), towerName: z.string(), communityName: z.string() }),
  worker: z.object({ id: uuidSchema, employeeCode: z.string(), fullName: z.string() }).nullable(),
  checkIn: z
    .object({
      eventId: uuidSchema,
      method: z.string(),
      at: z.string(),
      flags: z.array(z.string()),
      distanceM: z.number().nullable(),
      accuracyM: z.number().nullable(),
      reviewStatus: z.string(),
      reviewNote: z.string().nullable(),
    })
    .nullable(),
  rejectedAttempts: z.number().int(),
  completedAt: z.string().nullable(),
  noShow: z.object({ kind: z.string(), note: z.string().nullable() }).nullable(),
  feedback: z.object({ rating: z.number().int(), comment: z.string().nullable() }).nullable(),
});
export type AttendanceRecord = z.infer<typeof attendanceRecordSchema>;

export const reviewFlagSchema = z.object({ decision: z.enum(['ACCEPTED', 'REJECTED']), note: z.string().trim().min(3).max(500) });
export const workerNoShowSchema = z.object({ note: z.string().trim().min(3).max(500) });

export const correctionSchema = z.object({
  id: uuidSchema,
  occurrenceId: uuidSchema,
  scheduledDate: z.string(),
  flat: z.object({ flatNumber: z.string(), towerName: z.string(), communityName: z.string() }),
  worker: z.object({ id: uuidSchema, employeeCode: z.string(), fullName: z.string() }),
  requestedChange: z.enum(['MARK_ATTENDED', 'MARK_COMPLETED']),
  explanation: z.string(),
  status: z.enum(['PENDING', 'APPROVED', 'REJECTED']),
  reviewNote: z.string().nullable(),
  /** Original evidence, if any (rejected attempts or flagged check-in). */
  originalEvent: z.object({ result: z.string(), flags: z.array(z.string()), at: z.string() }).nullable(),
  createdAt: z.string(),
});
export type Correction = z.infer<typeof correctionSchema>;
export const decideCorrectionSchema = z.object({ decision: z.enum(['APPROVED', 'REJECTED']), note: z.string().trim().min(3).max(500) });

export const geofenceSchema = z.object({ radiusM: z.number().int().min(25).max(5000) });

// ---------------------------------------------------------------- feedback (ADM-12)

/** GET /feedback query: newest first, keyset paging. */
export const feedbackListQuerySchema = z.object({
  limit: z.coerce.number().int().min(1).max(100).default(25),
  cursor: z.string().min(1).optional(),
  communityId: uuidSchema.optional(),
  employeeId: uuidSchema.optional(),
  /** Ratings from minRating to maxRating inclusive (1-5). */
  minRating: z.coerce.number().int().min(1).max(5).optional(),
  maxRating: z.coerce.number().int().min(1).max(5).optional(),
  /** true = only feedback with a written comment. */
  withComment: z.enum(['true', 'false']).transform((v) => v === 'true').optional(),
});
export type FeedbackListQuery = z.infer<typeof feedbackListQuerySchema>;

export const adminFeedbackSchema = z.object({
  occurrenceId: uuidSchema,
  rating: z.number().int(),
  comment: z.string().nullable(),
  createdAt: z.string(),
  visitDate: z.string(),
  serviceName: z.string(),
  resident: z.object({ id: uuidSchema, fullName: z.string().nullable() }),
  worker: z.object({ id: uuidSchema, fullName: z.string(), employeeCode: z.string() }).nullable(),
  community: z.object({ id: uuidSchema, name: z.string() }),
  flat: z.object({ flatNumber: z.string(), towerName: z.string() }),
});
export type AdminFeedback = z.infer<typeof adminFeedbackSchema>;
